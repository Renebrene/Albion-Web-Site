def _commons(title: str, width: int = 1400) -> dict:
    params = {
        "action": "query",
        "titles": "File:" + title,
        "prop": "imageinfo",
        "iiprop": "url|extmetadata|size|mime",
        "iiurlwidth": str(width),
        "format": "json",
        "origin": "*",
    }
    url = "https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=40) as resp:
        data = json.load(resp)
    for page in data.get("query", {}).get("pages", {}).values():
        info = (page.get("imageinfo") or [{}])[0]
        if info.get("thumburl") or info.get("url"):
            return info
    raise RuntimeError(f"Файл не найден: {title}")


def _download(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=90) as resp:
        return resp.read()


def _plain(value) -> str:
    import re
    return re.sub(r"<[^>]+>", "", str(value or "")).strip()


def _locations(conn) -> dict:
    rows = conn.execute("SELECT id, label FROM home_geo_locations").fetchall()
    return {row[1]: row[0] for row in rows}


def run() -> None:
    print("ALBION · Наполнение geo-слайда: описания и обложки")

    with get_connection() as conn:
        loc = _locations(conn)
        lower = {k.lower(): v for k, v in loc.items()}

        def lid(label):
            return loc.get(label) or lower.get(label.lower())

        # 1. Описания
        for label, text in DESCRIPTIONS.items():
            location_id = lid(label)
            if not location_id:
                print(f"  · нет локации «{label}»")
                continue
            with conn.transaction():
                conn.execute(
                    "UPDATE home_geo_locations SET description = %s, updated_at = NOW() "
                    "WHERE id = %s",
                    (text, location_id),
                )
        print(f"  ✓ описания обновлены: {len(DESCRIPTIONS)}")

        # 2. Новые достопримечательности с фото
        for label, (file_name, atitle, adesc) in NEW_ATTRACTIONS.items():
            location_id = lid(label)
            if not location_id:
                print(f"  · нет локации «{label}»")
                continue

            exists = conn.execute(
                "SELECT 1 FROM home_geo_attractions WHERE location_id = %s LIMIT 1",
                (location_id,),
            ).fetchone()
            if exists:
                print(f"  · уже есть достопримечательность: {label}")
                continue

            try:
                info = _commons(file_name)
            except Exception as exc:
                print(f"  ! {label}: {exc}")
                continue

            meta = info.get("extmetadata") or {}
            image_url = info.get("thumburl") or info.get("url")
            source_url = info.get("descriptionurl") or ""
            license_name = _plain((meta.get("LicenseShortName") or {}).get("value"))
            artist = _plain((meta.get("Artist") or {}).get("value"))

            image_bytes = _download(image_url)
            media = save_image(image_bytes, file_name, alt=atitle, title=atitle)

            with conn.transaction():
                attraction_id = conn.execute(
                    "INSERT INTO home_geo_attractions "
                    "(location_id, title, description, sort_order, is_active) "
                    "VALUES (%s, %s, %s, 0, TRUE) RETURNING id",
                    (location_id, atitle, adesc),
                ).fetchone()[0]
                cred = "Wikimedia Commons"
                if artist:
                    cred = f"Wikimedia Commons · {artist}"
                conn.execute(
                    "INSERT INTO home_geo_attraction_photos "
                    "(attraction_id, media_id, image_path, alt_text, source_name, "
                    " source_url, license, sort_order, is_cover) "
                    "VALUES (%s, %s, %s, %s, %s, %s, %s, 0, TRUE)",
                    (attraction_id, media.get("id"), media.get("storage_path"),
                     atitle, cred, source_url, license_name),
                )
            print(f"  ✓ {label}: {atitle} ({license_name})")

        # 3. Обложки локаций
        with conn.transaction():
            conn.execute(
                "UPDATE home_geo_locations l SET cover_attraction_id = a.id "
                "FROM (SELECT DISTINCT ON (location_id) id, location_id "
                "      FROM home_geo_attractions WHERE location_id IS NOT NULL "
                "      ORDER BY location_id, sort_order, id) a "
                "WHERE a.location_id = l.id"
            )
        print("  ✓ обложки локаций выставлены")

    print("COMMIT: geo-контент готов.")


if __name__ == "__main__":
    run()
