def get_traffic_light_tab(conn) -> dict | None:
    """Получает закладку traffic-light из info_tabs."""
    row = conn.execute(
        """
        SELECT id, title, kind, content, sort_order, is_active
        FROM info_tabs
        WHERE kind = 'traffic-light'
        ORDER BY sort_order, id
        LIMIT 1
        """
    ).fetchone()

    if not row:
        return None

    return {
        "id": row[0],
        "title": row[1],
        "kind": row[2],
        "content": row[3],
        "sort_order": row[4],
        "is_active": row[5],
    }


def get_photos_from_category(conn, category_name: str) -> list[dict]:
    """Получает фотографии из категории медиа."""
    # Получаем id категории.
    cat_row = conn.execute(
        "SELECT id FROM media_categories WHERE name = %s",
        (category_name,),
    ).fetchone()

    if not cat_row:
        return []

    category_id = cat_row[0]

    # Получаем фотографии с card-вариантом.
    rows = conn.execute(
        """
        SELECT m.id, m.original_name, mv.storage_path, mv.variant, mv.width, mv.height
        FROM media m
        JOIN media_variants mv ON mv.media_id = m.id
        WHERE m.category_id @> ARRAY[%s]::bigint[]
          AND mv.variant = 'card'
        ORDER BY m.id
        LIMIT 10
        """
        , (category_id,)
    ).fetchall()

    photos = []
    for row in rows:
        photos.append({
            "url": f"/storage/{row[2]}",
            "label": row[1],
        })

    return photos


def init_content() -> None:
    """Инициализирует контент закладки светофорных объектов."""
    with get_connection() as conn:
        tab = get_traffic_light_tab(conn)

        if tab:
            print(f"Закладка «Светофорные объекты» уже существует (id={tab['id']})")
            print("Обновление контента...")

            # Получаем фотографии.
            photos = get_photos_from_category(conn, "Светофоры")
            print(f"  Найдено фотографий: {len(photos)}")

            # Собираем JSON контент.
            content = {
                "image_url": None,  # Можно установить изображение светофора.
                "text": TRAFFIC_LIGHT_TEXT,
                "photos": photos[:10],  # Первые 10 фотографий.
            }

            content_json = json.dumps(content, ensure_ascii=False, indent=2)

            # Обновляем закладку.
            conn.execute(
                """
                UPDATE info_tabs
                SET content = %s, updated_at = NOW()
                WHERE id = %s
                """,
                (content_json, tab["id"]),
            )

            print("  Контент обновлён.")
        else:
            print("Создаём закладку «Светофорные объекты»...")

            # Получаем фотографии.
            photos = get_photos_from_category(conn, "Светофоры")
            print(f"  Найдено фотографий: {len(photos)}")

            # Собираем JSON контент.
            content = {
                "image_url": None,
                "text": TRAFFIC_LIGHT_TEXT,
                "photos": photos[:10],
            }

            content_json = json.dumps(content, ensure_ascii=False, indent=2)

            # Создаём закладку.
            conn.execute(
                """
                INSERT INTO info_tabs (title, kind, content, sort_order, is_active)
                VALUES ('СВЕТОФОРНЫЕ ОБЪЕКТЫ', 'traffic-light', %s, 40, TRUE)
                """,
                (content_json,),
            )

            print("  Закладка создана.")

    print("\nГотово!")


